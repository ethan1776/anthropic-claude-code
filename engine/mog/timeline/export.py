"""Export the Timeline schema for the web app: JSON Schema + TypeScript types.

The TypeScript is generated from the Pydantic models, so the frontend and the engine can
never disagree about the timeline format. Run `python -m mog schema` after changing
models.py (a test fails if the committed files are stale).
"""

from __future__ import annotations

import json
from pathlib import Path

from mog.timeline.models import Timeline

HEADER = "// AUTO-GENERATED by `python -m mog schema` from engine/mog/timeline/models.py. Do not edit.\n"


def json_schema() -> dict:
    # "serialization" mode: describes JSON the engine *writes*, where defaults are filled in
    return Timeline.model_json_schema(mode="serialization")


def write_json_schema(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(json_schema(), indent=2) + "\n")
    return path


def _ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(dict.fromkeys(_ts_type(x) for x in s[key]))
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts_type(x) for x in s["prefixItems"]) + "]"
        inner = _ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        return "Record<string, unknown>"
    return "unknown"


def _interface(name: str, s: dict) -> str:
    lines = []
    if s.get("description"):
        lines.append("/** " + " ".join(s["description"].split()) + " */")
    lines.append(f"export interface {name} {{")
    required = set(s.get("required", []))
    for prop, ps in s.get("properties", {}).items():
        if ps.get("description"):
            lines.append(f"  /** {' '.join(ps['description'].split())} */")
        opt = "" if prop in required else "?"
        lines.append(f"  {prop}{opt}: {_ts_type(ps)};")
    lines.append("}")
    return "\n".join(lines)


def typescript() -> str:
    schema = json_schema()
    defs = dict(schema.get("$defs", {}))
    out = [HEADER]
    for name in sorted(defs):
        out.append(_interface(name, defs[name]))
    out.append(_interface("Timeline", schema))
    effect_names = ["ZoomPunch", "Shake", "Flash", "RgbSplit", "MotionBlur"]
    out.append("export type Effect = " + " | ".join(effect_names) + ";")
    return "\n\n".join(out) + "\n"


def write_typescript(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(typescript())
    return path
